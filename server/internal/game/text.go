// PhaseDiff 计算相性差（对应 GeneralListCache.get_phase_difference / get_d_phase）
func (w *World) PhaseDiff(a, b *entities.General) int {
	if a == nil || b == nil {
		return 0
	}
	d := a.Phase - b.Phase
	if d < 0 {
		d = -d
	}
	if d > 74 {
		d = 149 - d
	}
	return d
}
